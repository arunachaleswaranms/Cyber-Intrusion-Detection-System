"""Run the guarded one-time v2.0 evaluation on the official test partition."""

from __future__ import annotations

import argparse
import json
from datetime import datetime, timezone
from pathlib import Path

import pandas as pd

from cids.config import (
    DEFAULT_EXPERIMENT_CONFIG,
    config_sha256,
    load_experiment_config,
)
from cids.datasets.split_unsw_nb15 import prepare_splits
from cids.datasets.verify_manifest import DEFAULT_MANIFEST, verify_dataset
from cids.final_evaluation import save_artifact, train_and_evaluate_selected
from cids.final_protocol import (
    DEFAULT_FINAL_PROTOCOL,
    FINAL_CONFIRMATION_PHRASE,
    load_final_protocol,
    protocol_sha256,
    validate_reproduced_selection,
)
from cids.selection import (
    DEFAULT_MODEL_SELECTION,
    load_model_selection,
    selection_sha256,
)


class OfficialTestRunError(ValueError):
    """Raised before an unsafe or inconsistent final evaluation can start."""


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--data-dir", required=True, type=Path)
    parser.add_argument("--output-dir", required=True, type=Path)
    parser.add_argument("--reproduction-selection", required=True, type=Path)
    parser.add_argument("--confirm", required=True)
    parser.add_argument("--manifest", type=Path, default=DEFAULT_MANIFEST)
    parser.add_argument("--config", type=Path, default=DEFAULT_EXPERIMENT_CONFIG)
    parser.add_argument("--selection", type=Path, default=DEFAULT_MODEL_SELECTION)
    parser.add_argument("--protocol", type=Path, default=DEFAULT_FINAL_PROTOCOL)
    return parser.parse_args()


def _write_json(path: Path, value: dict) -> None:
    path.write_text(
        json.dumps(value, indent=2, sort_keys=True) + "\n",
        encoding="utf-8",
    )


def main() -> int:
    args = parse_args()
    if args.confirm != FINAL_CONFIRMATION_PHRASE:
        raise OfficialTestRunError(
            f"confirmation must be exactly {FINAL_CONFIRMATION_PHRASE!r}"
        )
    if args.output_dir.exists():
        raise OfficialTestRunError(
            f"final output directory already exists: {args.output_dir}"
        )
    if args.reproduction_selection.resolve() == args.selection.resolve():
        raise OfficialTestRunError(
            "reproduction selection must be generated by a clean validation rerun"
        )

    config = load_experiment_config(args.config)
    recorded_selection = load_model_selection(args.selection, config=config)
    reproduced_selection = load_model_selection(
        args.reproduction_selection,
        config=config,
    )
    validate_reproduced_selection(
        reproduced_selection,
        recorded_selection,
        config=config,
    )
    protocol = load_final_protocol(
        args.protocol,
        config=config,
        selection=recorded_selection,
    )
    verified = {item.role: item for item in verify_dataset(args.data_dir, args.manifest)}
    dataset_files = {
        role: {
            "filename": item.path.name,
            "records": item.records,
            "size_bytes": item.size_bytes,
            "sha256": item.sha256,
        }
        for role, item in verified.items()
    }

    args.output_dir.mkdir(parents=True, exist_ok=False)
    started_at = datetime.now(timezone.utc).isoformat()
    run_state_path = args.output_dir / "run_state.json"
    run_state = {
        "status": "in_progress",
        "started_at_utc": started_at,
        "official_test_status": "evaluation_started",
        "experiment_config_sha256": config_sha256(config),
        "model_selection_sha256": selection_sha256(recorded_selection, config),
        "reproduction_selection_sha256": selection_sha256(
            reproduced_selection, config
        ),
        "final_protocol_sha256": protocol_sha256(
            protocol,
            config=config,
            selection=recorded_selection,
        ),
        "dataset_files": dataset_files,
    }
    _write_json(run_state_path, run_state)

    official_train = pd.read_csv(verified["train"].path, encoding="utf-8-sig")
    official_test = pd.read_csv(verified["test"].path, encoding="utf-8-sig")
    task_results: dict[str, dict] = {}
    for task in ("binary", "multiclass"):
        splits = prepare_splits(
            official_train,
            official_test,
            task=task,
            validation_fraction=config["split"]["validation_fraction"],
            seed=config["split"]["seed"],
        )
        result = train_and_evaluate_selected(
            splits,
            config=config,
            selection=recorded_selection,
            protocol=protocol,
        )
        artifact_path = save_artifact(
            result.artifact,
            args.output_dir / f"{task}-{result.artifact.model_name}.joblib",
        )
        task_results[task] = {
            "artifact": artifact_path.name,
            "metadata": result.artifact.metadata,
            "split_report": splits.report,
            "official_test_metrics": result.official_test_metrics,
        }

    completed_at = datetime.now(timezone.utc).isoformat()
    report = {
        "report_version": "unsw-nb15-official-test-results-v1",
        "started_at_utc": started_at,
        "completed_at_utc": completed_at,
        "experiment_config_sha256": config_sha256(config),
        "model_selection_sha256": selection_sha256(recorded_selection, config),
        "reproduction_selection_sha256": selection_sha256(
            reproduced_selection, config
        ),
        "final_protocol_sha256": protocol_sha256(
            protocol,
            config=config,
            selection=recorded_selection,
        ),
        "dataset_files": dataset_files,
        "official_test_status": "evaluated_once",
        "tasks": task_results,
    }
    report_path = args.output_dir / "official_test_results.json"
    _write_json(report_path, report)
    run_state.update(
        {
            "status": "completed",
            "completed_at_utc": completed_at,
            "official_test_status": "evaluated_once",
            "results": report_path.name,
        }
    )
    _write_json(run_state_path, run_state)

    print(f"Wrote official-test results: {report_path}")
    for task, value in task_results.items():
        metrics = value["official_test_metrics"]
        print(
            f"{task}: model={value['metadata']['model_name']}, "
            f"macro_f1={metrics['f1_macro']:.4f}, "
            f"balanced_accuracy={metrics['balanced_accuracy']:.4f}"
        )
    print("Official test status: evaluated_once")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
